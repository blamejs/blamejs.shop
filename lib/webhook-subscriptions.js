  MAX_EVENT_TYPES:       MAX_EVENT_TYPES,
  MAX_EVENT_TYPE_LEN:    MAX_EVENT_TYPE_LEN,
  MAX_ENDPOINT_URL_LEN:  MAX_ENDPOINT_URL_LEN,
  SECRET_BYTES:          SECRET_BYTES,
  SECRET_NAMESPACE:      SECRET_NAMESPACE,
